-- ============================================================================
-- 0001_rituals.sql — public catalogue of rituals/services
-- ============================================================================
-- Target: PostgreSQL 15+ (Supabase). Idempotent: safe to re-run.
--
-- Apply with:  supabase db push
--       or:    paste into the Supabase SQL editor
--
-- Design note (the important part):
--   `image_path` stores a *file name only* — e.g. 'mahakal-puja.jpg'.
--   The browser appends the ImageKit host and the transform query at render
--   time. Consequences:
--     * no absolute URLs rot when the CDN domain changes;
--     * rows are ~200 bytes, so the 500 MB data tier is never the constraint;
--     * the 500 KB photo is never stored in Postgres.
--   Do NOT insert full https:// URLs here unless you are mid-migration.
-- ============================================================================

begin;

create table if not exists public.rituals (
  -- `bigint` matches the int8 contract; identity is preferred over serial
  -- because it does not leave an orphaned sequence behind.
  -- `by default` (not `always`) so the 14 existing services can be imported
  -- with their current ids, keeping any bookmarked URLs stable.
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  duration    text,
  price       text,
  image_path  text
);

comment on table public.rituals is
  'Public catalogue of Vedic rituals. Read-only for the browser (RLS select policy).';
comment on column public.rituals.image_path is
  'Relative ImageKit file name only (e.g. mahakal-puja.jpg). Never a full URL.';
comment on column public.rituals.duration is
  'Free text in the priest''s own words, e.g. "2–3 घंटे". Not a number: these are estimates.';
comment on column public.rituals.price is
  'Free text, e.g. "₹5,100 से". Deliberately text: dakshina is quoted per family.';

-- ---------------------------------------------------------------- security
-- The anon key ships in the browser bundle, so the table must be readable by
-- it *and nothing more*. RLS is what makes a public key safe.
alter table public.rituals enable row level security;

-- Defence in depth: strip the default grants, then hand back exactly one verb.
revoke all on public.rituals from anon, authenticated;
grant select on public.rituals to anon, authenticated;

drop policy if exists "rituals are publicly readable" on public.rituals;
create policy "rituals are publicly readable"
  on public.rituals
  for select
  to anon, authenticated
  using (true);

-- There is deliberately NO insert/update/delete policy.
-- => anon and authenticated cannot write, even though they hold SELECT.
--    When admin editing arrives, do not loosen this: add a server-side route
--    that uses the service_role key, or add a policy restricted to an admin
--    claim. Never ship service_role to the browser.

-- ----------------------------------------------------------------- ideology
-- No secondary indexes. This is intentional, not an oversight:
--   * the page does `select ... order by id`, which the primary-key index
--     already satisfies exactly (index scan, no sort);
--   * the table holds single-digit-to-low-double-digit rows, i.e. one or two
--     heap pages — a seq scan is cheaper than an index scan plus heap fetch;
--   * every extra index is write amplification for no read benefit.
-- Revisit only when a query filters on a column AND the table is large enough
-- to matter. Then measure first:
--
--   explain (analyze, buffers, format text)
--   select id, title, description, duration, price, image_path
--   from public.rituals
--   where title ilike '%रुद्र%'
--   order by id;
--
-- If that shows `Seq Scan` with a high row count, add a *trigram* index (not a
-- plain btree — btree cannot serve `ilike '%…%'`):
--   create extension if not exists pg_trgm;
--   create index concurrently rituals_title_trgm
--     on public.rituals using gin (title gin_trgm_ops);

commit;

